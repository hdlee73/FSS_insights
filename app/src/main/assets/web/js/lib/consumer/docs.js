// 요구서·신청서 초안 문안 만들기. 입력은 화면에서 받고 브라우저 안에서만 조립한다(서버 전송 없음).
import { VIOLATIONS, PRODUCT_TYPES } from "./rights.js";

const blank = (v, hint) => (v && String(v).trim() ? String(v).trim() : `【${hint}】`);
const kdate = (iso) => {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(iso || "");
  return m ? `${m[1]}년 ${+m[2]}월 ${+m[3]}일` : "【날짜】";
};

const FOOT = "※ 이 문서는 참고용 초안이며 법률자문이 아닙니다. 사실과 다른 내용은 고쳐서 사용하세요.";

/** 청약철회 의사표시서. */
export function withdrawalLetter(f) {
  const type = PRODUCT_TYPES[f.type]?.label || "금융상품";
  const refund = f.type === "loan"
    ? "대출 원금과 약정 이자, 그리고 금융회사가 제3자에게 이미 지급한 인지세·등기비용 등 법령이 정한 비용을 반환하겠습니다. 이를 반환한 때 철회의 효력이 발생하는 것으로 알고 있으므로, 반환할 금액과 계좌를 안내해 주시기 바랍니다."
    : "제가 낸 금전은 법 제46조 제3항에 따라 철회 접수일부터 3영업일 이내에 제가 지정하는 계좌로 반환해 주시기 바랍니다.";
  return [
    "청약 철회 의사표시서",
    "",
    `수신: ${blank(f.company, "금융회사명")} 귀중`,
    `발신: ${blank(f.name, "성명")} (연락처 ${blank(f.contact, "전화번호")})`,
    `작성일: ${kdate(f.date)}`,
    "",
    "1. 계약 내용",
    `  - 상품 구분: ${type}`,
    `  - 상품명: ${blank(f.product, "상품명")}`,
    `  - 계약(청약)일: ${kdate(f.contractDate)}`,
    `  - 계약번호: ${blank(f.contractNo, "계약번호")}`,
    "",
    "2. 철회 의사",
    "「금융소비자 보호에 관한 법률」 제46조에 따라 위 계약의 청약을 철회합니다. 이 서면(또는 전자우편·문자메시지)을 발송하는 날이 철회 기간 안임을 알려 드립니다.",
    "",
    "3. 반환 요청",
    refund,
    f.account ? `  - 반환받을 계좌: ${f.account}` : "  - 반환받을 계좌: 【은행명·계좌번호·예금주】",
    "",
    "4. 위약금 등",
    "법 제46조 제4항에 따라 청약 철회를 이유로 손해배상이나 위약금 등 금전을 청구할 수 없음을 알려 드립니다.",
    "",
    "5. 요청",
    "이 서면을 받으신 즉시 접수 확인(접수일)을 회신해 주시고, 처리 결과를 위 연락처로 알려 주시기 바랍니다.",
    "",
    `${kdate(f.date)}`,
    `${blank(f.name, "성명")} (서명 또는 인)`,
    "",
    FOOT,
  ].join("\n");
}

/** 위법계약해지 요구서. f.violations: 선택한 위반 id 배열. */
export function cancellationLetter(f) {
  const picked = VIOLATIONS.filter((v) => (f.violations || []).includes(v.id));
  const reasons = picked.length
    ? picked.map((v, i) => `  ${i + 1}) ${v.title} (${v.law})\n     ${v.text}`).join("\n")
    : "  【위반 유형을 선택하거나 직접 적어 주세요】";
  return [
    "위법계약 해지 요구서",
    "",
    `수신: ${blank(f.company, "금융회사명")} 귀중`,
    `발신: ${blank(f.name, "성명")} (연락처 ${blank(f.contact, "전화번호")})`,
    `작성일: ${kdate(f.date)}`,
    "",
    "1. 계약 내용",
    `  - 상품명: ${blank(f.product, "상품명")}`,
    `  - 계약번호: ${blank(f.contractNo, "계약번호")}`,
    `  - 계약체결일: ${kdate(f.contractDate)}`,
    `  - 위반 사실을 알게 된 날: ${kdate(f.knownDate)}`,
    "",
    "2. 해지 요구",
    "「금융소비자 보호에 관한 법률」 제47조 제1항에 따라 위 계약의 해지를 요구합니다.",
    "",
    "3. 위반 사항",
    reasons,
    "",
    "4. 구체적인 사실관계",
    f.facts && f.facts.trim() ? f.facts.trim().split("\n").map((l) => "  " + l).join("\n") : "  【가입 당시 상황을 날짜·담당자·들은 말 중심으로 적어 주세요. 예: 20XX. X. X. 영업점 방문, 담당자 OOO가 '원금 손실 가능성은 거의 없다'고 말함】",
    "",
    "5. 요구 사항",
    "  가. 위 계약을 위법계약으로 보아 해지하여 주시기 바랍니다.",
    "  나. 법 제47조 제3항에 따라 해지와 관련한 수수료·위약금 등 비용을 청구하지 않아야 함을 알려 드립니다.",
    "  다. 법 제47조 제1항에 따라 이 요구를 받은 날부터 10일 이내에 수락 여부를 통지하여 주시고, 거절하는 경우에는 그 사유를 함께 통지하여 주시기 바랍니다.",
    "",
    "6. 첨부",
    "  - 위반 사실을 증명하는 자료(계약서·상품설명서·녹취·문자·통화기록 등) 【해당 자료 목록】",
    "",
    `${kdate(f.date)}`,
    `${blank(f.name, "성명")} (서명 또는 인)`,
    "",
    FOOT,
  ].join("\n");
}

